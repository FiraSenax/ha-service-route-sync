"""Generate the standalone gateway reader from the canonical HA protocol sources."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "custom_components/service_route_sync/windows"
DESTINATION = ROOT / "gateway/windows_reader"
HEADER = "# Generated by scripts/sync_windows_reader.py; edit the canonical windows package.\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    mismatches = []
    for source in sorted(SOURCE.glob("windows_*.py")):
        target = DESTINATION / source.name
        expected = HEADER + source.read_text()
        if not target.exists() or target.read_text() != expected:
            mismatches.append(source.name)
            if not options.check:
                target.write_text(expected)
    if options.check and mismatches:
        raise SystemExit("Gateway reader differs from canonical sources: " + ", ".join(mismatches))


if __name__ == "__main__":
    main()
