"""Administrator-only atomic import into the inactive Lady live checkpoint."""

import asyncio
import voluptuous as vol
import hashlib
import json
import time

from homeassistant.core import SupportsResponse
from homeassistant.exceptions import ServiceValidationError
from homeassistant.helpers.service import async_register_admin_service

from .const import DOMAIN
from .lady_store import LadyCheckpointError, LadyCheckpointStore, validate_checkpoint
from .lady_history import LadyHistory, LadyHistoryError, journal_path


def revision_number(value):
    if type(value) is not int or value < 0:
        raise vol.Invalid("Expected a nonnegative revision")
    return value


def freeze_import(checkpoint, events):
    encoded = json.dumps(
        {"checkpoint": checkpoint, "events": events},
        sort_keys=True,
        ensure_ascii=False,
        allow_nan=False,
    ).encode()
    if len(encoded) > 16 * 1024 * 1024:
        raise LadyCheckpointError("Imported history exceeds size bound")
    return hashlib.sha256(encoded).hexdigest(), json.loads(encoded)["events"]


def register_lady_services(hass):
    if hass.services.has_service(DOMAIN, "import_lady_checkpoint"):
        return
    locks = {}

    async def import_checkpoint(call):
        if not call.context.user_id:
            raise ServiceValidationError("An authenticated administrator is required for import")
        entry = hass.config_entries.async_get_entry(call.data["entry_id"])
        if entry is None or entry.domain != DOMAIN:
            raise ServiceValidationError("Unknown Service Route Sync entry")
        async with locks.setdefault(entry.entry_id, asyncio.Lock()):
            settings = {**entry.data, **entry.options}
            runtime = getattr(entry, "runtime_data", None)
            lady = getattr(runtime, "lady", None)
            if (
                not settings.get("lady_enabled")
                or settings.get("lady_active", False)
                or lady is None
                or lady.active
            ):
                raise ServiceValidationError("Lady must be loaded in observation mode for import")
            try:
                candidate = await hass.async_add_executor_job(
                    validate_checkpoint, call.data["checkpoint"]
                )
                if "history_revision" in candidate or "history_epoch" in candidate:
                    raise LadyCheckpointError("Import metadata must be generated by this service")
                if not isinstance(candidate["cursor"], dict) or "day" not in candidate["cursor"]:
                    raise LadyCheckpointError("Verified daily cursor is required")
                store = LadyCheckpointStore(hass, entry.entry_id)
                existing = await store.async_load()
                expected = call.data["expected_revision"]
                if expected != store.revision:
                    raise LadyCheckpointError("Imported checkpoint was superseded")
                epoch, events = await hass.async_add_executor_job(
                    freeze_import, candidate, call.data["history_events"]
                )
                if existing is not None and existing.get("history_epoch") == epoch:
                    return {"imported": False, "revision": store.revision}
                candidate.update(history_epoch=epoch, history_revision=expected + 1)
                history = LadyHistory(
                    journal_path(hass.config.path(DOMAIN, "lady_history"), store.store.key, epoch)
                )

                async def prepare_history():
                    await hass.async_add_executor_job(
                        history.prepare_import, expected + 1, time.time(), events
                    )

                revision = await store.async_commit(
                    candidate, expected_revision=expected, before_save=prepare_history
                )
                return {"imported": True, "revision": revision}
            except (
                LadyCheckpointError,
                LadyHistoryError,
                OSError,
                ValueError,
                TypeError,
                UnicodeError,
            ):
                raise ServiceValidationError(
                    "Lady checkpoint import could not be committed"
                ) from None

    async_register_admin_service(
        hass,
        DOMAIN,
        "import_lady_checkpoint",
        import_checkpoint,
        schema=vol.Schema(
            {
                vol.Required("entry_id"): str,
                vol.Required("checkpoint"): dict,
                vol.Required("history_events"): vol.All(list, vol.Length(max=100000)),
                vol.Optional("expected_revision", default=0): revision_number,
            }
        ),
        supports_response=SupportsResponse.OPTIONAL,
    )
